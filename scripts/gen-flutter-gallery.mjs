// Writes flutter/lib/gallery/registry.dart: one entry per flutter/lib/examples/<name>.dart, with the title, category and description of the React component of the same name.
// Run: node scripts/gen-flutter-gallery.mjs
import fs from 'node:fs';

const reg = fs.readFileSync('src/registry/index.ts', 'utf8');
const meta = {};
for (const m of reg.matchAll(/^  m\('([a-z0-9-]+)', '((?:[^'\\]|\\.)*)', '([A-Za-z]+)', '((?:[^'\\]|\\.)*)'/gm)) meta[m[1]] = { name: m[2].replace(/\\(.)/g, '$1'), category: m[3], description: m[4].replace(/\\(.)/g, '$1') };

const files = fs.readdirSync('flutter/lib/examples').filter((f) => f.endsWith('.dart')).map((f) => f.replace(/\.dart$/, '')).sort();
const dart = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$');
const rows = files.map((f) => {
  const slug = f.replace(/_/g, '-');
  const m = meta[slug];
  if (!m) { console.warn(`gallery: no React component named ${slug}, skipped`); return null; }
  const hasPreview = /^Widget preview\(/m.test(fs.readFileSync(`flutter/lib/examples/${f}.dart`, 'utf8'));
  return { f, slug, hasPreview, ...m };
}).filter(Boolean);

const out = `// Generated by scripts/gen-flutter-gallery.mjs from flutter/lib/examples. Add a widget by adding befui/<name>.dart and examples/<name>.dart, then run the script.
import 'package:flutter/widgets.dart';

${rows.map((r) => `import '../examples/${r.f}.dart' as e_${r.f};`).join('\n')}

class GalleryEntry {
  const GalleryEntry(this.slug, this.name, this.category, this.description, this.example, [this.preview]);
  final String slug, name, category, description;
  final Widget Function(BuildContext) example;

  /// A static picture of what the example opens (a dialog panel, a menu), used for the screenshots on the site.
  final Widget Function(BuildContext)? preview;
}

final List<GalleryEntry> entries = [
${rows.map((r) => `  GalleryEntry('${r.slug}', '${dart(r.name)}', '${r.category}', '${dart(r.description)}', e_${r.f}.example${r.hasPreview ? `, e_${r.f}.preview` : ''}),`).join('\n')}
];
`;
fs.writeFileSync('flutter/lib/gallery/registry.dart', out);
console.log(`flutter gallery: ${rows.length} entries`);
