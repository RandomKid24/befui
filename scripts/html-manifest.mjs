// Writes src/html/manifest.ts: tag -> [file, export] for every component in src/components/ui, so the HTML build can load a component's code only when its tag shows up.
import fs from 'node:fs';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();

export function buildManifest() {
  const m = {};
  for (const f of fs.readdirSync('src/components/ui').filter((x) => x.endsWith('.tsx')).sort()) {
    const src = fs.readFileSync(`src/components/ui/${f}`, 'utf8');
    for (const [, name] of src.matchAll(/^export (?:const|function) ([A-Z]\w*)/gm)) {
      if (/^[A-Z][A-Z0-9_]+$/.test(name)) continue; // constants like COUNTRIES
      const tag = `bef-${kebab(name)}`;
      if (!m[tag]) m[tag] = [f.replace(/\.tsx$/, ''), name];
    }
  }
  return m;
}

export const manifestSource = () =>
  `// Generated by scripts/html-manifest.mjs (npm run build:html). Do not edit.\nexport const manifest: Record<string, [file: string, name: string]> = ${JSON.stringify(buildManifest(), null, 1).replace(/\n\s*/g, ' ').replace(/\], /g, '],\n  ').replace(/^\{ /, '{\n  ').replace(/ \}$/, '\n}')};\n`;

if (process.argv[1]?.endsWith('html-manifest.mjs')) {
  fs.writeFileSync('src/html/manifest.ts', manifestSource());
  console.log(`manifest: ${Object.keys(buildManifest()).length} tags`);
}
