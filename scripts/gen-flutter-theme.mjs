// Writes flutter/lib/befui/theme.dart from the same tokens the React components use (src/index.css and src/registry/themes.json),
// so a colour or radius change is made once. Run: node scripts/gen-flutter-theme.mjs
import fs from 'node:fs';

const css = fs.readFileSync('src/index.css', 'utf8');
const block = (re) => Object.fromEntries([...(css.match(re)?.[1] ?? '').matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const light = block(/:root, \.light \{([\s\S]*?)\n\}/);
const dark = block(/\n\.dark \{([\s\S]*?)\n\}/);
const themes = JSON.parse(fs.readFileSync('src/registry/themes.json', 'utf8'));

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const KEYS = ['background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground', 'primary', 'primary-foreground', 'secondary', 'secondary-foreground', 'muted', 'muted-foreground', 'accent', 'accent-foreground', 'border', 'input', 'ring', 'destructive', 'success', 'warning', 'info'];
const hex = (v) => `Color(0xFF${v.replace('#', '').toUpperCase()})`;
const colors = (m) => `BefColors(\n${KEYS.map((k) => `    ${camel(k)}: ${hex(m[k])},`).join('\n')}\n  )`;

const palette = (name, t) => `  static const ${name} = BefPalette(
    label: '${t.label}',
    light: ${colors({ ...light, ...t.light })},
    dark: ${colors({ ...dark, ...t.dark })},
  );`;

const out = `// Generated by scripts/gen-flutter-theme.mjs from src/index.css and src/registry/themes.json. Edit those, not this file... or edit this file freely once it is in your app.
import 'package:flutter/material.dart';

/// The befui colour tokens. Same names as the CSS variables: --primary is [primary], --muted-foreground is [mutedForeground].
@immutable
class BefColors {
  const BefColors({
${KEYS.map((k) => `    required this.${camel(k)},`).join('\n')}
  });

${KEYS.map((k) => `  final Color ${camel(k)};`).join('\n')}

  BefColors copyWith({${KEYS.map((k) => `Color? ${camel(k)}`).join(', ')}}) => BefColors(
${KEYS.map((k) => `        ${camel(k)}: ${camel(k)} ?? this.${camel(k)},`).join('\n')}
      );

  static BefColors lerp(BefColors a, BefColors b, double t) => BefColors(
${KEYS.map((k) => `        ${camel(k)}: Color.lerp(a.${camel(k)}, b.${camel(k)}, t)!,`).join('\n')}
      );
}

/// A light and a dark set of colours, like one entry of the Themes page.
@immutable
class BefPalette {
  const BefPalette({required this.label, required this.light, required this.dark});
  final String label;
  final BefColors light;
  final BefColors dark;

  BefColors of(Brightness b) => b == Brightness.dark ? dark : light;

${Object.entries(themes).map(([n, t]) => palette(n, t)).join('\n\n')}

  static const all = <BefPalette>[${Object.keys(themes).join(', ')}];
}

/// Corner radii: --radius is ${light.radius}, and the CSS scale is sm = radius - 2, lg = radius + 2, xl = radius + 6.
class BefRadius {
  static const double base = 8;
  static const double sm = base - 2;
  static const double md = base;
  static const double lg = base + 2;
  static const double xl = base + 6;
  static const double full = 9999;
}

/// The theme extension that carries befui colours. Add it to your [ThemeData] with [BefTheme.data] and read it anywhere with \`context.bef\`.
@immutable
class BefTheme extends ThemeExtension<BefTheme> {
  const BefTheme({required this.colors, this.fontFamily = 'Inter', this.monoFamily = 'JetBrains Mono'});

  final BefColors colors;

  /// Inter on the docs site. It falls back to the platform font when the family is not bundled, so add Inter (google_fonts or an asset) to match exactly.
  final String fontFamily;
  final String monoFamily;

  @override
  BefTheme copyWith({BefColors? colors, String? fontFamily, String? monoFamily}) =>
      BefTheme(colors: colors ?? this.colors, fontFamily: fontFamily ?? this.fontFamily, monoFamily: monoFamily ?? this.monoFamily);

  @override
  BefTheme lerp(ThemeExtension<BefTheme>? other, double t) =>
      other is BefTheme ? BefTheme(colors: BefColors.lerp(colors, other.colors, t), fontFamily: fontFamily, monoFamily: monoFamily) : this;

  /// A full [ThemeData] for [brightness] with the befui extension and Material defaults tuned to match (ripple, text selection, scaffold colour).
  static ThemeData data({Brightness brightness = Brightness.light, BefPalette palette = BefPalette.blue, String fontFamily = 'Inter'}) {
    final c = palette.of(brightness);
    final scheme = ColorScheme(
      brightness: brightness,
      primary: c.primary,
      onPrimary: c.primaryForeground,
      secondary: c.secondary,
      onSecondary: c.secondaryForeground,
      error: c.destructive,
      onError: Colors.white,
      surface: c.background,
      onSurface: c.foreground,
    );
    return ThemeData(
      useMaterial3: true,
      brightness: brightness,
      colorScheme: scheme,
      scaffoldBackgroundColor: c.background,
      canvasColor: c.background,
      dividerColor: c.border,
      fontFamily: fontFamily,
      splashFactory: InkRipple.splashFactory,
      highlightColor: Colors.transparent,
      textSelectionTheme: TextSelectionThemeData(cursorColor: c.primary, selectionColor: c.primary.withValues(alpha: 0.25)),
      extensions: [BefTheme(colors: c, fontFamily: fontFamily)],
    );
  }

  static BefTheme of(BuildContext context) =>
      Theme.of(context).extension<BefTheme>() ?? BefTheme(colors: BefPalette.blue.of(Theme.of(context).brightness));
}

extension BefContext on BuildContext {
  /// The befui colours of the nearest theme: \`context.bef.primary\`.
  BefColors get bef => BefTheme.of(this).colors;
}

/// Text styles on the Tailwind scale the React components use (text-xs 12, text-sm 14, text-base 16...). Colour defaults to the foreground token.
class BefText {
  static TextStyle style(BuildContext context, {double size = 14, FontWeight weight = FontWeight.w400, Color? color, double? height, double? letterSpacing, bool mono = false}) {
    final t = BefTheme.of(context);
    return TextStyle(
      fontFamily: mono ? t.monoFamily : t.fontFamily,
      fontSize: size,
      fontWeight: weight,
      color: color ?? t.colors.foreground,
      height: height ?? (size <= 12 ? 16 / size : size <= 14 ? 20 / size : size <= 16 ? 24 / size : size <= 18 ? 28 / size : 1.25),
      letterSpacing: letterSpacing,
      decoration: TextDecoration.none,
    );
  }
}

/// The two shadows the CSS uses most: shadow-sm and shadow-md.
class BefShadow {
  static const sm = [BoxShadow(color: Color(0x0D000000), blurRadius: 2, offset: Offset(0, 1))];
  static const md = [BoxShadow(color: Color(0x1A000000), blurRadius: 6, offset: Offset(0, 4), spreadRadius: -1), BoxShadow(color: Color(0x1A000000), blurRadius: 4, offset: Offset(0, 2), spreadRadius: -2)];
}
`;
fs.mkdirSync('flutter/lib/befui', { recursive: true });
fs.writeFileSync('flutter/lib/befui/theme.dart', out);
console.log('flutter theme: ' + Object.keys(themes).length + ' palettes');
