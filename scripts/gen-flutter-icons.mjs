// Writes flutter/lib/befui/icons.dart from src/components/ui/icons.tsx: the same hand-drawn icons, as paths painted by BefIcon (no icon package, no SVG package).
// Run: node scripts/gen-flutter-icons.mjs
import fs from 'node:fs';

const src = fs.readFileSync('src/components/ui/icons.tsx', 'utf8');
const names = [];
const defs = [];
for (const m of src.matchAll(/^export const (\w+) = make\('(\w+)', (\[[\s\S]*?\])\);$/gm)) {
  const [, name, , body] = m;
  const shapes = new Function('p', `return ${body}`)((d) => ['path', d]);
  const dart = shapes.map((s) => (s[0] === 'path' ? `BefShape.path(${JSON.stringify(s[1]).replace(/\$/g, '\\$')})` : s[0] === 'circle' ? `BefShape.circle(${s.slice(1).join(', ')})` : `BefShape.rect(${s.slice(1).join(', ')})`)).join(', ');
  const id = (name === 'BefMark' ? 'befMark' : name.replace(/Icon$/, '').replace(/^[A-Z]/, (c) => c.toLowerCase())).replace(/^(\d)/, '_$1');
  names.push(id);
  defs.push(`  static const ${id} = BefIconData([${dart}]);`);
}

const out = `// Generated by scripts/gen-flutter-icons.mjs from src/components/ui/icons.tsx. ${names.length} icons on one 24px grid, drawn as strokes. No packages needed.
import 'package:flutter/widgets.dart';

/// One piece of an icon: a path, a circle or a rounded rectangle, in 24 x 24 units.
@immutable
class BefShape {
  const BefShape.path(String this.d)
      : x = 0,
        y = 0,
        w = 0,
        h = 0,
        r = 0,
        kind = 0;
  const BefShape.circle(this.x, this.y, this.r)
      : d = null,
        w = 0,
        h = 0,
        kind = 1;
  const BefShape.rect(this.x, this.y, this.w, this.h, this.r)
      : d = null,
        kind = 2;
  final int kind;
  final String? d;
  final double x, y, w, h, r;
}

@immutable
class BefIconData {
  const BefIconData(this.shapes);
  final List<BefShape> shapes;
}

/// All icons: \`BefIcon(BefIcons.search)\`.
class BefIcons {
${defs.join('\n')}
}

/// An icon at [size] logical pixels (default 16, like the React components). Colour defaults to the surrounding [IconTheme], so it follows buttons and text.
class BefIcon extends StatelessWidget {
  const BefIcon(this.icon, {super.key, this.size, this.color, this.weight = 1.75, this.semanticLabel});
  final BefIconData icon;
  final double? size;
  final Color? color;

  /// Stroke width on the 24px grid.
  final double weight;
  final String? semanticLabel;

  @override
  Widget build(BuildContext context) {
    final theme = IconTheme.of(context);
    final s = size ?? (theme.size ?? 16);
    final c = color ?? theme.color ?? const Color(0xFF000000);
    return Semantics(
      label: semanticLabel,
      image: semanticLabel != null,
      excludeSemantics: semanticLabel == null,
      child: SizedBox(width: s, height: s, child: CustomPaint(painter: _IconPainter(icon, c, weight))),
    );
  }
}

class _IconPainter extends CustomPainter {
  _IconPainter(this.icon, this.color, this.weight);
  final BefIconData icon;
  final Color color;
  final double weight;

  static final _paths = <String, Path>{};

  @override
  void paint(Canvas canvas, Size size) {
    final k = size.width / 24;
    canvas.save();
    canvas.scale(k);
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = weight
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
    for (final s in icon.shapes) {
      switch (s.kind) {
        case 0:
          canvas.drawPath(_paths.putIfAbsent(s.d!, () => parseSvgPath(s.d!)), paint);
        case 1:
          canvas.drawCircle(Offset(s.x, s.y), s.r, paint);
        default:
          canvas.drawRRect(RRect.fromRectAndRadius(Rect.fromLTWH(s.x, s.y, s.w, s.h), Radius.circular(s.r)), paint);
      }
    }
    canvas.restore();
  }

  @override
  bool shouldRepaint(_IconPainter old) => old.icon != icon || old.color != color || old.weight != weight;
}

/// Parses the SVG path data the icons use: M L H V C S Q T A Z, absolute and relative.
Path parseSvgPath(String d) {
  final path = Path();
  final n = RegExp(r'[-+]?(?:\\d*\\.\\d+|\\d+\\.?)(?:[eE][-+]?\\d+)?');
  var i = 0;
  var cmd = '';
  double cx = 0, cy = 0, sx = 0, sy = 0, lx = 0, ly = 0;
  String last = '';
  double num() {
    final m = n.matchAsPrefix(d, i)!;
    i = m.end;
    while (i < d.length && (d[i] == ' ' || d[i] == ',')) {
      i++;
    }
    return double.parse(m[0]!);
  }

  bool flag() {
    final v = d[i] == '1';
    i++;
    while (i < d.length && (d[i] == ' ' || d[i] == ',')) {
      i++;
    }
    return v;
  }

  bool more() {
    while (i < d.length && (d[i] == ' ' || d[i] == ',')) {
      i++;
    }
    return i < d.length;
  }

  while (more()) {
    if (RegExp(r'[A-Za-z]').hasMatch(d[i])) {
      cmd = d[i++];
    }
    final rel = cmd == cmd.toLowerCase();
    final c = cmd.toUpperCase();
    final ox = rel ? cx : 0.0, oy = rel ? cy : 0.0;
    switch (c) {
      case 'M':
        cx = ox + num();
        cy = oy + num();
        sx = cx;
        sy = cy;
        path.moveTo(cx, cy);
        cmd = rel ? 'l' : 'L';
      case 'L':
        cx = ox + num();
        cy = oy + num();
        path.lineTo(cx, cy);
      case 'H':
        cx = (rel ? cx : 0) + num();
        path.lineTo(cx, cy);
      case 'V':
        cy = (rel ? cy : 0) + num();
        path.lineTo(cx, cy);
      case 'C':
        final x1 = ox + num(), y1 = oy + num(), x2 = ox + num(), y2 = oy + num();
        cx = ox + num();
        cy = oy + num();
        path.cubicTo(x1, y1, x2, y2, cx, cy);
        lx = x2;
        ly = y2;
      case 'S':
        final x1 = last == 'C' || last == 'S' ? 2 * cx - lx : cx, y1 = last == 'C' || last == 'S' ? 2 * cy - ly : cy;
        final x2 = ox + num(), y2 = oy + num();
        cx = ox + num();
        cy = oy + num();
        path.cubicTo(x1, y1, x2, y2, cx, cy);
        lx = x2;
        ly = y2;
      case 'Q':
        final x1 = ox + num(), y1 = oy + num();
        cx = ox + num();
        cy = oy + num();
        path.quadraticBezierTo(x1, y1, cx, cy);
        lx = x1;
        ly = y1;
      case 'T':
        final x1 = last == 'Q' || last == 'T' ? 2 * cx - lx : cx, y1 = last == 'Q' || last == 'T' ? 2 * cy - ly : cy;
        cx = ox + num();
        cy = oy + num();
        path.quadraticBezierTo(x1, y1, cx, cy);
        lx = x1;
        ly = y1;
      case 'A':
        final rx = num(), ry = num(), rot = num();
        final large = flag(), sweep = flag();
        cx = ox + num();
        cy = oy + num();
        path.arcToPoint(Offset(cx, cy), radius: Radius.elliptical(rx, ry), rotation: rot, largeArc: large, clockwise: sweep);
      case 'Z':
        path.close();
        cx = sx;
        cy = sy;
      default:
        return path;
    }
    last = c;
  }
  return path;
}
`;
fs.writeFileSync('flutter/lib/befui/icons.dart', out);
console.log(`flutter icons: ${names.length}`);
